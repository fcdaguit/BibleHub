package com.sermonstudio.app.data.ai

import com.sermonstudio.app.data.bible.BibleRef

enum class SermonType(val label: String) {
    TOPICAL("Topical Sermon"),
    EXPOSITORY("Expository Sermon"),
    TEXTUAL("Textual Sermon"),
    DEVOTIONAL("Devotional Message"),
    BIBLE_STUDY("Bible Study Lesson"),
    LEADERSHIP("Leadership Teaching"),
    YOUTH("Youth Message"),
    SMALL_GROUP("Small Group Guide"),
}

/** Exactly one of [topic] / [passage] is normally set. */
data class SermonRequest(
    val topic: String? = null,
    val passage: BibleRef? = null,
    val type: SermonType = SermonType.TOPICAL,
    val versionId: String,
)

data class SermonPoint(val heading: String, val scriptures: List<String>, val explanation: String)

data class SermonDraft(
    val title: String,
    val theme: String,
    val mainText: String,
    val background: String = "",
    val introduction: String,
    val points: List<SermonPoint>,
    val crossReferences: List<String>,
    val illustrations: List<String>,
    val applications: List<String>,
    val discussionQuestions: List<String>,
    val conclusion: String,
    val invitation: String,
    /** "template" or "llm" - shown to the user so they know what produced the draft. */
    val engine: String,
)

interface SermonEngine {
    val id: String
    suspend fun generate(req: SermonRequest): SermonDraft
}

/** Converts a draft into the editor's markup so it can be saved as a normal sermon outline. */
object OutlineFormatter {
    private val roman = listOf("I", "II", "III", "IV", "V", "VI", "VII", "VIII")

    fun toMarkup(d: SermonDraft): String = buildString {
        appendLine("# ${d.title}")
        if (d.theme.isNotBlank()) appendLine("> Theme: ${d.theme}")
        if (d.mainText.isNotBlank()) appendLine("**Main Text:** ${d.mainText}")
        appendLine()
        if (d.background.isNotBlank()) { appendLine("## Background"); appendLine(d.background); appendLine() }
        appendLine("## Introduction"); appendLine(d.introduction); appendLine()
        d.points.forEachIndexed { i, p ->
            appendLine("## ${roman.getOrElse(i) { "${i + 1}" }}. ${p.heading}")
            if (p.scriptures.isNotEmpty()) appendLine("- Scripture: ${p.scriptures.joinToString("; ")}")
            if (p.explanation.isNotBlank()) appendLine(p.explanation)
            appendLine()
        }
        fun list(title: String, items: List<String>, numbered: Boolean = false) {
            if (items.isEmpty()) return
            appendLine("## $title")
            items.forEachIndexed { i, s -> appendLine(if (numbered) "${i + 1}. $s" else "- $s") }
            appendLine()
        }
        list("Cross References", d.crossReferences)
        list("Illustrations", d.illustrations)
        list("Application", d.applications, numbered = true)
        list("Discussion Questions", d.discussionQuestions)
        appendLine("## Conclusion"); appendLine(d.conclusion); appendLine()
        appendLine("## Invitation"); appendLine("==${d.invitation}==")
        appendLine()
        appendLine("> Draft generated by the ${d.engine} engine - verify every verse and teaching before preaching.")
    }
}
